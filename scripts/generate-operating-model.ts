#!/usr/bin/env tsx
/**
 * Generate the MSP operating model document from the model in code.
 *
 * The document is a view, not a claim. `packages/domain/src/operating-model.ts`
 * is the source and `tests/unit/operating-model.test.ts` checks it against the
 * authority model, the surface model and the commercial states. Running this
 * turns that verified data into something an MSP can read.
 *
 * `pnpm docs:operating-model` writes it; CI runs the same command and fails if
 * the committed file differs, so the document cannot drift from the system the
 * way a hand-written diagram does.
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import {
  ACCOUNT_STATE_MEANINGS,
  CLIENT_APPROVAL_POINTS,
  ESCALATION_PATHS,
  EVIDENCE_OWNERSHIP,
  OPERATING_ACTORS,
  REVIEW_RESPONSIBILITIES,
  operatingModelDiscrepancies,
} from '@adericel/domain';

const OUT = path.join(process.cwd(), 'docs', 'product', 'MSP_OPERATING_MODEL.md');

function render(): string {
  const discrepancies = operatingModelDiscrepancies();

  const lines: string[] = [
    '<!-- Generated by scripts/generate-operating-model.ts. Do not edit by hand. -->',
    '<!-- Source: packages/domain/src/operating-model.ts -->',
    '',
    '# The Adericel MSP Operating Model',
    '',
    'Who does what, who owns what, and where a decision goes when it cannot be',
    'made where it arose.',
    '',
    '**This document is generated from the system.** It is rendered from',
    '`packages/domain/src/operating-model.ts`, which',
    '`tests/unit/operating-model.test.ts` checks against the authority model, the',
    'surface model and the commercial states. A diagram drawn by hand is true on',
    'the day it is drawn and then quietly reassures everybody about a system that',
    'has moved on; this cannot, because CI fails if it drifts.',
    '',
  ];

  if (discrepancies.length > 0) {
    lines.push(
      '> **This model does not currently match the implementation.** The following',
      '> discrepancies were found when this document was generated, and are printed',
      '> rather than hidden:',
      '',
      ...discrepancies.map((problem) => `> - ${problem}`),
      '',
    );
  }

  lines.push(
    '## The four parties',
    '',
    '| Party | What they are |',
    '| ----- | ------------- |',
    '| **Veylith Systems** | Builds and operates the platform. Not a party to the client relationship, and holds no standing access to client data. |',
    '| **The MSP** | Holds the contract with the client and the credentials to their estate. Adericel’s customer. |',
    '| **The client organisation** | Whose security posture is being assured. Owns the evidence and the record. |',
    '| **Evidence sources** | Cloud tenants, endpoint managers, documents, people. What the record is built from. |',
    '',
    '## Who decides what',
    '',
  );

  for (const actor of OPERATING_ACTORS) {
    lines.push(
      `### ${actor.name}`,
      '',
      `**Party:** ${actor.party} · **Role:** \`${actor.role}\` · **Surface:** \`${actor.surface}\``,
      '',
      `${actor.accountableFor}`,
      '',
    );
    if (actor.decidesAlone.length > 0) {
      lines.push(
        'Decides alone:',
        '',
        ...actor.decidesAlone.map((permission) => `- \`${permission}\``),
        '',
      );
    } else {
      lines.push('Decides nothing alone — read access only.', '');
    }
    lines.push('Never does:', '', ...actor.neverDoes.map((never) => `- ${never}`), '');
  }

  lines.push(
    '## Evidence ownership',
    '',
    'The evidence describes the client and belongs to them. The MSP holds the',
    'credential because they administer the estate; that is custody, not',
    'ownership. Veylith reads none of it.',
    '',
    '| Source | Credential held by | Readable by | Leaves with |',
    '| ------ | ------------------ | ----------- | ----------- |',
    ...EVIDENCE_OWNERSHIP.map(
      (ownership) =>
        `| ${ownership.sourceKind} | ${ownership.credentialHeldBy} | ${ownership.readableBy.join(', ')} | **${ownership.leavesWith}** |`,
    ),
    '',
    ...EVIDENCE_OWNERSHIP.flatMap((ownership) => [
      `**${ownership.sourceKind}.** ${ownership.note}`,
      '',
    ]),
    '## Review responsibilities',
    '',
    'Every row says whether the system **enforces** the review or merely',
    '**surfaces** it. The distinction matters and most vendors blur it:',
    '"exceptions are reviewed" reads as a control, but if nothing stops an',
    'unreviewed exception expiring then it is a reminder. Both are useful. They',
    'are not the same promise.',
    '',
    '| What | Reviewed by | When | |',
    '| ---- | ----------- | ---- | - |',
    ...REVIEW_RESPONSIBILITIES.map(
      (review) =>
        `| ${review.what} | ${review.by} | ${review.trigger} | ${review.enforcement === 'ENFORCED' ? '**Enforced**' : 'Surfaced'} |`,
    ),
    '',
    '## Escalation paths',
    '',
    ...ESCALATION_PATHS.flatMap((path) => [
      `**${path.from} → ${path.to}** — ${path.about}`,
      '',
      path.note,
      '',
    ]),
    '## What the client has to approve',
    '',
    'Not the MSP on their behalf. These are the points where the client is the',
    'only party who can say yes.',
    '',
    ...CLIENT_APPROVAL_POINTS.flatMap((point) => [`**${point.what}.** ${point.why}`, '']),
    '## Account and entitlement state',
    '',
    'Ten commercial states, and what each means for the two parties who have to',
    'live with it. A commercial state is never a security state: non-payment is',
    'not a containment, and no state withholds the client’s own record.',
    '',
    '| State | For the MSP | For the client |',
    '| ----- | ----------- | -------------- |',
    ...ACCOUNT_STATE_MEANINGS.map(
      (meaning) => `| \`${meaning.state}\` | ${meaning.forTheMsp} | ${meaning.forTheClient} |`,
    ),
    '',
    '## Data retention and offboarding',
    '',
    'A client leaves with their record. That is the whole position, and it is',
    'enforced rather than promised:',
    '',
    '- Every commercial state, including `TERMINATED`, permits reading and',
    '  exporting the organisation’s own assurance record.',
    '- The Assurance Passport exports as a signed envelope a recipient verifies',
    '  without an Adericel account and without a network call.',
    '- Erasure means erasure: a deletion request removes the data rather than',
    '  flagging it, and the audit record of the deletion is what remains.',
    '- Retention is a policy per organisation, not a platform default, because',
    '  the obligation belongs to the client and their regulator.',
    '',
    'See [ADR-0030](../adr/ADR-0030-offboarding.md) and',
    '[ADR-0032](../adr/ADR-0032-erasure-and-retention.md).',
    '',
    '## What this model deliberately does not do',
    '',
    '- **No Veylith access to client data as a normal state.** Support that needs',
    '  it uses break-glass: four hours maximum, justified, second factor required,',
    '  the MSP told at the time, visible in the client’s own audit trail, reviewed',
    '  afterwards whether or not it turned out to be warranted.',
    '- **No Adericel-to-client relationship by default.** A client request routes',
    '  to their MSP, enforced in routing and again in reassignment. Direct support',
    '  requires a signed agreement, and that gate ships granted to nobody.',
    '- **No single score.** Coverage and satisfaction are reported separately and',
    '  there is no function that combines them.',
    '- **No approval by an agent.** Four-eyes is structural: the proposer’s',
    '  identity cannot approve, and a service identity has no approval permission',
    '  to be granted.',
    '',
  );

  return lines.join('\n');
}

const content = render();
writeFileSync(OUT, content, 'utf8');
console.log(`wrote ${path.relative(process.cwd(), OUT)} (${content.length} bytes)`);

const discrepancies = operatingModelDiscrepancies();
if (discrepancies.length > 0) {
  console.error(
    `\n${discrepancies.length} discrepancy(ies) between the operating model and the implementation:`,
  );
  for (const problem of discrepancies) console.error(`  - ${problem}`);
  process.exitCode = 1;
}
