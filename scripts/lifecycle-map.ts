import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  ACTION_STATES,
  EXECUTION_REALISATION,
  EXECUTION_STAGES,
  STAGE_OF_ACTION_STATE,
  SUPPORT_STAGES,
  unmappedActionStates,
  unrealisedExecutionStages,
} from '@adericel/domain';
import {
  SUPPORT_CASE_STATES,
  STAGE_OF_CASE_STATE,
  caseStatesInStage,
  caseStatesOutsideTheLifecycle,
  unoccupiedSupportStages,
} from '@adericel/support';

/**
 * The correspondence between the lifecycles the contract states and the ones
 * this system runs, rendered for the person who wrote the contract.
 *
 * WHY A DOCUMENT AND NOT JUST THE CODE
 *
 * RR-080 asked for the correspondence to be stated in code rather than prose,
 * and it is: two total records, each refusing to compile when a state is added
 * without being assigned. But the reason the gap mattered was that *nobody
 * could check it* — not the contract's author, not an auditor — without holding
 * two documents open and reading twenty-plus identifiers against fifteen.
 *
 * So the records are rendered. The code keeps the correspondence true; this
 * makes it readable, and makes the places where the shapes genuinely differ
 * visible to the person entitled to object to them.
 */

const ROOT = join(import.meta.dirname, '..');
const OUT = join(ROOT, 'docs', 'product', 'CONTRACT_LIFECYCLE_MAP.md');

export function render(): string {
  const unoccupied = unoccupiedSupportStages();
  const outside = caseStatesOutsideTheLifecycle();
  const unrealised = unrealisedExecutionStages();
  const unmapped = unmappedActionStates();

  const supportRows = SUPPORT_STAGES.map((stage) => {
    const states = caseStatesInStage(stage);
    return `| \`${stage}\` | ${states.length} | ${states.map((s) => `\`${s}\``).join(', ')} |`;
  }).join('\n');

  const executionRows = EXECUTION_STAGES.map((stage) => {
    const realisation = EXECUTION_REALISATION[stage];
    const states = realisation.actionStates;
    return (
      `| \`${stage}\` | ${realisation.realisation} | ` +
      `${states.length === 0 ? '—' : states.map((s) => `\`${s}\``).join(', ')} | ` +
      `${realisation.by} |`
    );
  }).join('\n');

  return `# The contract's lifecycles, against the ones this system runs

**Documentation state:** IMPLEMENTED

> **Generated by \`scripts/lifecycle-map.ts\`. Do not edit by hand.**
> \`tests/unit/lifecycle-map-doc.test.ts\` fails if this drifts from what the
> generator produces.

The contract states two lifecycles. This system implements both with more
states than the contract names, which is a refinement rather than a departure —
but until the mapping below existed, nothing said so, and a reader could not
tell a deliberate refinement from a stage that had been quietly dropped
(RR-080).

Both mappings are total records in code: adding a state is a compile error
until somebody decides which stated stage it belongs to. This document is that
decision, read back.

## The support lifecycle

Seven stated stages against ${SUPPORT_CASE_STATES.length} implemented states.

| Stated stage | States | Which |
| --- | --- | --- |
${supportRows}

**Stated stages nothing occupies: ${unoccupied.length === 0 ? 'none.' : unoccupied.join(', ')}**
${
  unoccupied.length === 0
    ? 'Every stage the contract names has at least one state behind it.'
    : 'Each of these is an obligation nothing in this system currently meets.'
}

States that belong to no stage, deliberately: ${outside.map((s) => `\`${s}\``).join(', ')}.
The stated lifecycle is a path to resolution, and these are endings that are
not resolutions. Recording either as \`RESOLVED\` or \`CLOSED\` would make a case
that was refused indistinguishable from one that was fixed.

## The execution lifecycle

Eight stated stages against ${ACTION_STATES.length} implemented action states.
A stage is not always a state, and the mapping says which it is rather than
pretending otherwise.

| Stated stage | How it is realised | Action states | By what |
| --- | --- | --- | --- |
${executionRows}

**Stated stages nothing realises: ${unrealised.length === 0 ? 'none.' : unrealised.join(', ')}**

Action states no stage claims: ${
    unmapped.length === 0 ? 'none.' : unmapped.map((s) => `\`${s}\``).join(', ')
  }
${
  unmapped.length === 0
    ? ''
    : 'These are endings and divergences rather than steps along the forward path.'
}

## What this document does not do

It records the correspondence; it does not enforce the **order**. Nothing here
stops a case or an action moving between states in a sequence the stated
lifecycle forbids — the prohibited-transition tables govern that, and the two
are not yet joined. Stated here because a reader would reasonably assume
otherwise.

Counted: ${Object.keys(STAGE_OF_CASE_STATE).length} support states and ${
    Object.keys(STAGE_OF_ACTION_STATE).length
  } action states, every one assigned or explicitly not.
`;
}

const rendered = render();
if (process.argv.includes('--check')) {
  process.stdout.write(rendered);
} else {
  writeFileSync(OUT, rendered, 'utf8');
  process.stdout.write(`wrote ${OUT}\n`);
}
