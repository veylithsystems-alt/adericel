#!/usr/bin/env tsx
/**
 * Generate the capability status document from the register.
 *
 * Contract v3.1 §6 requires a status per capability with no status inferable
 * from another; RR-052 records that it was tracked by hand in audit documents.
 * A status tracked by hand goes stale without anybody deciding that it should,
 * which is the failure mode this product exists to refuse in its customers'
 * systems and has no business tolerating in its own.
 *
 * `pnpm docs:capability-status` writes it; CI runs the same command and fails
 * if the committed file differs.
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import {
  CAPABILITY_STATUSES,
  HUMAN_ESTABLISHED_STATUSES,
  positionOf,
  registerProblems,
} from '@adericel/domain';
import { CAPABILITY_REGISTER } from './capability-register.js';

const OUT = path.join(process.cwd(), 'docs', 'product', 'CAPABILITY_STATUS.md');

function render(): string {
  const problems = registerProblems(CAPABILITY_REGISTER);
  const positions = CAPABILITY_REGISTER.map((capability) => positionOf(capability));

  const lines: string[] = [
    '<!-- Generated by scripts/generate-capability-status.ts. Do not edit by hand. -->',
    '<!-- Source: scripts/capability-register.ts -->',
    '',
    '# Capability status',
    '',
    'What state each capability in Adericel is actually in, and what establishes',
    'it.',
    '',
    '**This document is generated from the register.** It is rendered from',
    '[`capability-register.ts`](../../scripts/capability-register.ts) against the',
    'model in [`capability.ts`](../../packages/domain/src/capability.ts), and CI',
    'fails if the committed file differs. A status tracked by hand goes stale',
    'without anybody deciding that it should.',
    '',
    '## The rule that does all the work',
    '',
    'Contract v3.1 §6: **no status may be inferred from another.** Each',
    'capability carries an independent attestation per status, each naming its own',
    'evidence. A capability attested `OPERATIONAL` with no `VERIFIED` attestation',
    'has skipped the step where an invariant gets proved by deliberately breaking',
    'it — and that shows below as a skip rather than being quietly filled in.',
    '',
    'Three statuses cannot be established by anything in this repository:',
    '',
  ];

  for (const status of HUMAN_ESTABLISHED_STATUSES) {
    lines.push(`- \`${status}\``);
  }
  lines.push(
    '',
    'They are claims about the world outside it — a real customer used it, a named',
    'person would stand behind it in a dispute, somebody paid and stayed. A green',
    'pipeline is not evidence of any of them, and',
    '`attestationProblems()` refuses an automated attestation of all three.',
    '',
    '## Where each capability stands',
    '',
    '| Capability | Attested to | Skipped | Remaining |',
    '| --- | --- | --- | --- |',
  );

  for (const position of positions) {
    lines.push(
      `| ${position.title} | ${position.attested === null ? '_nothing_' : `\`${position.attested}\``} ` +
        `| ${position.skipped.length === 0 ? '—' : position.skipped.map((s) => `\`${s}\``).join(', ')} ` +
        `| ${position.notYetEstablished.length === 0 ? '—' : `${position.notYetEstablished.length}`} |`,
    );
  }

  lines.push('', '## What establishes each status', '');

  for (const capability of CAPABILITY_REGISTER) {
    const position = positionOf(capability);
    lines.push(`### ${capability.title}`, '', position.statement, '');
    const byStatus = new Map(capability.attestations.map((a) => [a.status, a]));
    for (const status of CAPABILITY_STATUSES) {
      const attestation = byStatus.get(status);
      if (!attestation) continue;
      lines.push(
        `- **${status}** (${attestation.source === 'NAMED_PERSON' ? 'person' : 'check'}) — ` +
          `${attestation.evidence}`,
      );
    }
    lines.push('');
  }

  if (problems.length > 0) {
    lines.push(
      '## Problems in the register',
      '',
      'The register refuses these attestations. Their presence in a committed file',
      'means we shipped a claim the model itself rejects.',
      '',
    );
    for (const entry of problems) {
      for (const problem of entry.problems) {
        lines.push(`- \`${entry.key}\` — ${problem}`);
      }
    }
    lines.push('');
  }

  lines.push(
    '## What this means for production readiness',
    '',
    'No capability in Adericel is attested `PROVEN`, `PRODUCTION_READY` or',
    '`COMMERCIAL_VALIDATED`, because none of them has run for a real customer.',
    'Adericel is **not production ready**, and this document is the place that',
    'says so rather than an audit note somebody has to remember to update.',
    '',
  );

  return `${lines.join('\n')}`;
}

writeFileSync(OUT, render(), 'utf8');
process.stdout.write(`wrote ${path.relative(process.cwd(), OUT)}\n`);
