import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { HUMAN_ESTABLISHED_STATUSES, positionOf, registerProblems } from '@adericel/domain';
import { CAPABILITY_REGISTER } from '../../scripts/capability-register.js';

const ROOT = new URL('../..', import.meta.url).pathname;
const DOC = 'docs/product/CAPABILITY_STATUS.md';

/**
 * The capability register, kept honest.
 *
 * Contract v3.1 §6 and RR-052. A register is only worth having if its evidence
 * is real, so this file checks the register against the repository rather than
 * against itself. The path-existence test is the important one: an evidence
 * string naming a test file that was renamed or deleted is a claim with nothing
 * behind it that still reads as substantiated — which is precisely the failure
 * the register was built to end.
 */

/** Every repository path any attestation cites. */
function citedPaths(): readonly { key: string; status: string; cited: string }[] {
  const pattern = /[A-Za-z0-9_./-]+\/[A-Za-z0-9_./-]+\.(?:ts|sql|sh|json|md|yml)/g;
  return CAPABILITY_REGISTER.flatMap((capability) =>
    capability.attestations.flatMap((attestation) =>
      [...attestation.evidence.matchAll(pattern)].map((match) => ({
        key: capability.key,
        status: attestation.status,
        cited: match[0],
      })),
    ),
  );
}

describe('the capability register', () => {
  it('cites paths, not just prose', () => {
    // A guard on the guard. If the pattern stops matching — an escaping change,
    // a rewrite of the evidence style — the existence test below would pass by
    // finding nothing to check, which is the quietest way for a test to stop
    // doing its job.
    expect(citedPaths().length).toBeGreaterThan(20);
  });

  it('cites only paths that exist', () => {
    const missing = citedPaths().filter(({ cited }) => !existsSync(path.join(ROOT, cited)));
    expect(
      missing,
      `The register cites paths that do not exist:\n${missing
        .map(({ key, status, cited }) => `  ${key} / ${status} -> ${cited}`)
        .join('\n')}`,
    ).toEqual([]);
  });

  it('holds no attestation the model itself refuses', () => {
    const problems = registerProblems(CAPABILITY_REGISTER);
    expect(
      problems,
      `The register holds refused attestations:\n${problems
        .map((entry) => `  ${entry.key}: ${entry.problems.join('; ')}`)
        .join('\n')}`,
    ).toEqual([]);
  });

  it('claims no capability is proven, production ready or commercially validated', () => {
    /**
     * §42 forbids claiming production readiness without the gates, and no
     * capability here has run for a real customer. The day one has, this test
     * is the thing that has to be changed deliberately — which is the point.
     */
    const overclaimed = CAPABILITY_REGISTER.filter((capability) =>
      capability.attestations.some((attestation) =>
        HUMAN_ESTABLISHED_STATUSES.includes(attestation.status),
      ),
    );
    expect(overclaimed.map((capability) => capability.key)).toEqual([]);
  });

  it('gives every capability a distinct key', () => {
    const keys = CAPABILITY_REGISTER.map((capability) => capability.key);
    expect(new Set(keys).size).toBe(keys.length);
  });

  it('reports the one capability that skipped a status, rather than filling it in', () => {
    // Backup and restore runs in CI and nobody has proved corruption detection
    // by deliberately corrupting a dump. The register says so on its own,
    // without anybody writing the sentence.
    const skips = CAPABILITY_REGISTER.map((capability) => positionOf(capability)).filter(
      (position) => position.skipped.length > 0,
    );
    expect(skips.map((position) => position.key)).toEqual(['backup-restore']);
    expect(skips[0]?.skipped).toEqual(['VERIFIED']);
  });
});

describe('the generated capability status document', () => {
  it('matches what the generator produces right now', () => {
    const committed = readFileSync(`${ROOT}${DOC}`, 'utf8');
    execFileSync('pnpm', ['-s', 'docs:capability-status'], { cwd: ROOT, stdio: 'pipe' });
    const regenerated = readFileSync(`${ROOT}${DOC}`, 'utf8');
    expect(
      regenerated === committed,
      `${DOC} is out of date. Run \`pnpm docs:capability-status\` and commit the result.`,
    ).toBe(true);
  }, 60_000);

  it('says it is generated, so nobody edits it by hand', () => {
    const committed = readFileSync(`${ROOT}${DOC}`, 'utf8');
    expect(committed).toMatch(/^<!-- Generated by/);
    expect(committed).toMatch(/Do not edit by hand/);
    expect(committed).toMatch(/scripts\/capability-register\.ts/);
  });

  it('states plainly that Adericel is not production ready', () => {
    const committed = readFileSync(`${ROOT}${DOC}`, 'utf8');
    expect(committed).toMatch(/not production ready/);
  });

  it('carries no problems section, because the register holds none', () => {
    // The generator writes a problems section into the document when the
    // register holds an attestation the model refuses. Its presence in a
    // committed file would mean we shipped a claim we know to be invalid.
    const committed = readFileSync(`${ROOT}${DOC}`, 'utf8');
    expect(committed).not.toMatch(/## Problems in the register/);
  });
});
