import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { CE_V3_3_REQUIREMENTS, summariseCeCoverage } from '@adericel/policy';
import { describe, expect, it } from 'vitest';

/**
 * The one number a commercial conversation needs, kept true.
 *
 * The machinery to compute Cyber Essentials coverage existed for weeks and
 * nothing printed the answer. The coverage test asserts no figure — correctly,
 * since it moves as connectors land — so "how many of the twenty-six
 * requirements can Adericel actually see" was computable and unrecorded. An
 * MSP asks it first.
 *
 * `docs/product/CYBER_ESSENTIALS_COVERAGE.md` is generated. These tests make
 * the generated document the only version that can exist, and make the honesty
 * of its framing mechanical rather than a matter of whoever last edited it.
 */

const ROOT = join(import.meta.dirname, '..', '..');
const DOC = join(ROOT, 'docs', 'product', 'CYBER_ESSENTIALS_COVERAGE.md');

function generated(): string {
  // Run the generator rather than importing it, so this fails if the script
  // itself has stopped working — the failure mode of every generated artefact.
  return execFileSync('npx', ['tsx', 'scripts/ce-coverage.ts', '--check'], {
    cwd: ROOT,
    encoding: 'utf8',
    maxBuffer: 16 * 1024 * 1024,
  });
}

/** Prettier reformats the committed file, so compare on content not layout. */
function normalise(markdown: string): string {
  return markdown
    .replaceAll(/\s+/g, ' ')
    .replaceAll(/\|\s+/g, '|')
    .replaceAll(/\s+\|/g, '|')
    .replaceAll(/-{2,}/g, '--')
    .trim();
}

describe('the Cyber Essentials coverage document', () => {
  const committed = readFileSync(DOC, 'utf8');

  it('says it is generated, so nobody edits it by hand', () => {
    expect(committed).toMatch(/Generated by `scripts\/ce-coverage\.ts`/);
    expect(committed).toMatch(/Do not edit by hand/i);
  });

  it('matches what the generator produces right now', () => {
    /**
     * The drift check. A coverage figure maintained by hand is a number that
     * was true once, and this is the document somebody will put in front of a
     * buyer.
     */
    expect(normalise(committed)).toBe(normalise(generated()));
  });

  it('states the measured figure, not a rounded boast', () => {
    const summary = summariseCeCoverage();
    expect(committed).toContain(
      `**${summary.observed} of ${summary.total} requirements are observed end to end.**`,
    );
    // Every requirement is accounted for in one of the four buckets, so the
    // document cannot state a coverage figure while quietly omitting rows.
    const accounted =
      summary.observed + summary.partial + summary.attestedOnly + summary.notObservable;
    expect(accounted, 'the four buckets do not account for every requirement').toBe(summary.total);
  });

  it('never claims compliance, certification or readiness', () => {
    /**
     * The contract's rule, applied to the document most likely to break it.
     * "No statement such as 'GDPR compliant' or 'fully compliant' may be made
     * merely because documentation exists" — and a coverage document is
     * exactly the documentation that tempts somebody into it.
     */
    /**
     * Only phrases that cannot appear innocently.
     *
     * A cleverer pattern for "certified" was tried and matched the document's
     * own disclaimer — "No statement here means an organisation is certified"
     * — which is the trap of judging prose by regex, refused elsewhere in this
     * repository for the same reason. The disclaimer is asserted positively
     * below instead, which is the stronger half anyway.
     */
    const forbidden = [
      /\bfully compliant\b/i,
      /\bis compliant\b/i,
      /\bcompliance guaranteed\b/i,
      /\bfull coverage\b/i,
      /\b100%\s*cover/i,
      /\bcertification achieved\b/i,
      /\bassessment[- ]ready\b/i,
    ];
    const offending = forbidden.filter((pattern) => pattern.test(committed)).map(String);
    expect(offending, 'the coverage document makes a compliance claim').toEqual([]);
    // And it says the opposite, in so many words.
    expect(committed).toMatch(/No statement here means an organisation is certified/i);
  });

  it('carries the caveat the summary itself insists on', () => {
    // The caveat travels with the number, in the summary's own words, so the
    // document cannot state the figure and drop the qualification.
    expect(committed).toContain(summariseCeCoverage().caveat);
  });

  it('declares how many paraphrases are unchecked against the scheme', () => {
    /**
     * The limit that matters most and is easiest to forget: the requirements
     * were written from working knowledge, so this document currently describes
     * Adericel's coverage of its own model of Cyber Essentials. Stating the
     * count means the claim gets weaker, visibly, until somebody does the work.
     */
    const unchecked = CE_V3_3_REQUIREMENTS.filter((r) => !r.sourceChecked).length;
    expect(committed).toContain(
      `**${unchecked} of the ${CE_V3_3_REQUIREMENTS.length} requirement paraphrases have not been`,
    );
  });

  it('names every requirement, and the predicates each one still lacks', () => {
    for (const requirement of CE_V3_3_REQUIREMENTS) {
      expect(committed, `${requirement.id} is missing from the document`).toContain(
        `\`${requirement.id}\``,
      );
    }
    // A gap row with no reason is the thing this document exists to prevent:
    // every requirement Adericel does not observe explains why.
    const unexplained = CE_V3_3_REQUIREMENTS.filter(
      (requirement) => requirement.observability !== 'OBSERVED' && requirement.note === null,
    ).map((requirement) => requirement.id);
    expect(unexplained, 'these are not observed and give no reason').toEqual([]);
  });
});
