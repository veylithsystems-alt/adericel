import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';

const ROOT = new URL('../..', import.meta.url).pathname;
const DOC = 'docs/product/MSP_OPERATING_MODEL.md';

/**
 * A generated document must equal what the generator produces.
 *
 * This is the test that makes "generated from the system" mean something. A
 * generator nobody runs is a document that has drifted, and a drifted
 * operating model is worse than no operating model: an MSP plans their
 * business around it and it reassures them about authority that has changed.
 *
 * The same shape guards the n8n export (a drift check on the committed file),
 * for the same reason.
 */
describe('the generated operating model', () => {
  it('matches what the generator produces right now', () => {
    const committed = readFileSync(`${ROOT}${DOC}`, 'utf8');

    execFileSync('pnpm', ['-s', 'docs:operating-model'], { cwd: ROOT, stdio: 'pipe' });
    const regenerated = readFileSync(`${ROOT}${DOC}`, 'utf8');

    expect(
      regenerated === committed,
      `${DOC} is out of date. Run \`pnpm docs:operating-model\` and commit the result.`,
    ).toBe(true);
  }, 60_000);

  it('says it is generated, so nobody edits it by hand', () => {
    const committed = readFileSync(`${ROOT}${DOC}`, 'utf8');
    expect(committed).toMatch(/^<!-- Generated by/);
    expect(committed).toMatch(/Do not edit by hand/);
    expect(committed).toMatch(/packages\/domain\/src\/operating-model\.ts/);
  });

  it('carries no discrepancy banner, because there are none', () => {
    // The generator prints a warning block into the document when the model
    // and the implementation disagree. Its presence in a committed file would
    // mean we shipped a model we know to be wrong.
    const committed = readFileSync(`${ROOT}${DOC}`, 'utf8');
    expect(committed).not.toMatch(/does not currently match the implementation/);
  });
});
