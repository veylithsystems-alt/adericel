import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { ACTION_STATES, SUPPORT_STAGES } from '@adericel/domain';
import { SUPPORT_CASE_STATES } from '@adericel/support';
import { describe, expect, it } from 'vitest';

/**
 * The rendered correspondence, kept true.
 *
 * RR-080 asked for the lifecycle mapping to be stated in code, and it is — two
 * total records that refuse to compile when a state is added unassigned. But
 * the reason the gap mattered was that nobody could *check* it without holding
 * two documents open, so the records are rendered for the person entitled to
 * object to them: the contract's author.
 *
 * These tests exist because a generated document that nothing checks is a
 * document that silently stops describing the system.
 */

const ROOT = join(import.meta.dirname, '..', '..');
const DOC = join(ROOT, 'docs', 'product', 'CONTRACT_LIFECYCLE_MAP.md');

function generated(): string {
  // Run the generator rather than importing it, so this fails if the script
  // itself breaks — the failure mode of every generated artefact.
  /**
   * `--conditions=development` so the generator resolves workspace packages to
   * their source, the way this repository's own dev scripts do.
   *
   * Without it the subprocess resolves `@adericel/*` to `dist`, which exists
   * after a build and not before — so this passed locally and failed in CI's
   * unit job, which deliberately does not build. Running the generator rather
   * than importing it is still the right call, because it fails when the script
   * itself breaks; it just has to run the way a developer runs it.
   */
  return execFileSync(
    'npx',
    ['tsx', '--conditions=development', 'scripts/lifecycle-map.ts', '--check'],
    {
      cwd: ROOT,
      encoding: 'utf8',
      maxBuffer: 16 * 1024 * 1024,
    },
  );
}

/** Prettier reformats the committed file, so compare content and not layout. */
function normalise(markdown: string): string {
  return markdown
    .replaceAll(/\s+/g, ' ')
    .replaceAll(/\|\s+/g, '|')
    .replaceAll(/\s+\|/g, '|')
    .replaceAll(/-{2,}/g, '--')
    .trim();
}

describe('the contract lifecycle map', () => {
  const committed = readFileSync(DOC, 'utf8');

  it('says it is generated, so nobody edits it by hand', () => {
    expect(committed).toMatch(/Generated by `scripts\/lifecycle-map\.ts`/);
    expect(committed).toMatch(/Do not edit by hand/i);
  });

  it('matches what the generator produces right now', () => {
    expect(normalise(committed)).toBe(normalise(generated()));
  });

  it('names every stated stage and every implemented state', () => {
    // The document's whole purpose is that a reader can check the mapping
    // without the code. One omitted row and they cannot.
    for (const stage of SUPPORT_STAGES) {
      expect(committed, `stated support stage ${stage} is missing`).toContain(`\`${stage}\``);
    }
    for (const state of SUPPORT_CASE_STATES) {
      expect(committed, `support state ${state} is missing`).toContain(`\`${state}\``);
    }
    for (const state of ACTION_STATES) {
      expect(committed, `action state ${state} is missing`).toContain(`\`${state}\``);
    }
  });

  it('states the two counts it is a mapping between', () => {
    expect(committed).toContain(
      `Counted: ${SUPPORT_CASE_STATES.length} support states and ${ACTION_STATES.length} action states`,
    );
  });

  it('says what it does not do, rather than letting a reader assume', () => {
    /**
     * The mapping records the correspondence and does not enforce the order.
     * A reader would reasonably assume otherwise — "the lifecycle is mapped"
     * sounds like "the lifecycle is enforced" — and leaving that unsaid is the
     * same class of overclaim as a coverage figure without its caveat.
     */
    expect(committed).toMatch(/does not enforce the \*\*order\*\*/);
    expect(committed).toMatch(/prohibited-transition tables/);
  });
});
